CHARS = [chr(c) for c in range(32, 128)] + ['\u2665', '\u25b6']

def build(path):
    from PIL import Image
    n = len(CHARS); cols = 16; rows = (n + cols - 1) // cols
    im = Image.new('RGBA', (cols * 6, rows * 8), (0, 0, 0, 0))
    for i, ch in enumerate(CHARS):
        g = G.get(ch) or G.get(ch.upper())
        if not g: continue
        ox, oy = (i % cols) * 6, (i // cols) * 8
        for y, row in enumerate(g):
            for x, c in enumerate(row):
                if c == '1': im.putpixel((ox + x, oy + y), (255, 255, 255, 255))
    im.save(path)
    return ''.join(CHARS)

def render_text(txt, col=(255, 255, 255), scale=1):
    """for use inside art generation: returns PIL image"""
    from PIL import Image
    im = Image.new('RGBA', (len(txt) * 6 * scale, 7 * scale), (0, 0, 0, 0))
    for i, ch in enumerate(txt):
        g = G.get(ch) or G.get(ch.upper())
        if not g: continue
        for y, row in enumerate(g):
            for x, c in enumerate(row):
                if c == '1':
                    for dx in range(scale):
                        for dy in range(scale): im.putpixel((i * 6 * scale + x * scale + dx, y * scale + dy), col + (255,))
    return im
